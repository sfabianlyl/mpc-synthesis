<?php

namespace App\Models;

// \Illuminate\Contracts\Auth\MustVerifyEmail;
use App\Models\ConsensusNote;
use App\Models\Diocese;
use App\Models\Extraction;

use Database\Factories\UserFactory;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Attributes\Hidden;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\BelongsToMany;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\Relations\HasOne;
use Illuminate\Foundation\Auth\User as Authenticatable;
use Illuminate\Notifications\Notifiable;
use Illuminate\Support\Carbon;

/**
 * @property int $id
 * @property string $name
 * @property string $email
 * @property string $role
 * @property int|null $diocese_id
 * @property Carbon|null $email_verified_at
 * @property string $password
 * @property string|null $two_factor_secret
 * @property string|null $two_factor_recovery_codes
 * @property Carbon|null $two_factor_confirmed_at
 * @property string|null $remember_token
 * @property Carbon|null $created_at
 * @property Carbon|null $updated_at
 * @property-read \Illuminate\Database\Eloquent\Collection<int, ConversationGroup> $assignedConversationGroups
 * @property-read \Illuminate\Database\Eloquent\Collection<int, FinalDocument> $draftedBooklets
 * @property-read \Illuminate\Database\Eloquent\Collection<int, ConsensusNote> $consensusNotes
 * @property-read \Illuminate\Database\Eloquent\Collection<int, Extraction> $extractions
 * @property-read \Illuminate\Database\Eloquent\Collection<int, SynthesisDraft> $synthesisDrafts
 * @property-read Diocese|null $diocese
 */
#[Fillable(['name', 'email', 'password', 'role', 'diocese_id'])]
#[Hidden(['password', 'two_factor_secret', 'two_factor_recovery_codes', 'remember_token'])]
class User extends Authenticatable
{
    /** @use HasFactory<UserFactory> */
    use HasFactory, Notifiable;

    /**
     * Get the attributes that should be cast.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'email_verified_at' => 'datetime',
            'password' => 'hashed',
        ];
    }

    /**
     * Check if the user has the given role.
     */
    public function hasRole(string $role): bool
    {
        return $this->role === $role;
    }

    /**
     * Check if user is a pastoral role member.
     */
    public function isPastoral(): bool
    {
        return $this->hasRole('pastoral');
    }

    /**
     * Check if user is a discernment role member.
     */
    public function isDiscernment(): bool
    {
        return $this->hasRole('discernment');
    }

    /**
     * Check if user is a synthesis team member.
     *
     * Deprecated: Previously included 'secretary' as a fallback for backward compatibility.
     * The 'secretary' role has been migrated to 'synthesis'.
     */
    public function isSynthesis(): bool
    {
        return $this->hasRole('synthesis');
    }

    /**
     * Check if user is a drafter.
     */
    public function isDrafter(): bool
    {
        return $this->hasRole('drafter');
    }

    /**
     * Check if user is an admin.
     */
    public function isAdmin(): bool
    {
        return $this->hasRole('admin');
    }

    /**
     * Get the diocese this user belongs to.
     */
    public function diocese(): BelongsTo
    {
        return $this->belongsTo(Diocese::class, 'diocese_id');
    }

    /**
     * Get the groups assigned to this synthesis team member.
     */
    public function assignedConversationGroups(): BelongsToMany
    {
        return $this->belongsToMany(ConversationGroup::class, 'conversation_group_user')
            ->withPivot('is_synthesizer')
            ->withTimestamps();
    }

    // Get all responses the user is allowed to view
    public function accessibleResponses()
    {
        return Response::whereIn(
            'conversation_group_id', 
            $this->assignedConversationGroups()->select('conversation_groups.id')
        );
    }

    /**
     * Get the booklets drafted/generated by this user.
     */
    public function draftedBooklets(): HasMany
    {
        return $this->hasMany(FinalDocument::class, 'drafted_by');
    }

    
    /**
     * Get the consensus notes written by this user.
     */
    public function consensusNotes(): HasMany
    {
        return $this->hasMany(ConsensusNote::class, 'user_id');
    }

    /**
     * Get the extractions performed by this user.
     */
    public function extractions(): HasMany
    {
        return $this->hasMany(Extraction::class, 'user_id');
    }

    /**
     * Get the synthesis drafts created by this user.
     */
    public function synthesisDrafts(): HasMany
    {
        return $this->hasMany(SynthesisDraft::class, 'user_id');
    }

    /**
     * Get the national decision drafts created by this user.
     */
    public function nationalDecisionDrafts(): HasMany
    {
        return $this->hasMany(NationalDecisionDraft::class, 'user_id');
    }

}
